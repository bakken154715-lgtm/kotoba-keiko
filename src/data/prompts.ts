export const PROMPTS: Prompt[] = GENRES.flatMap((genre) =>
  SOURCE[genre].map((text, index) => ({ id: `${genre}-${index}`, genre, text })),
);

export function findPrompt(id: string): Prompt | undefined {
  return PROMPTS.find((prompt) => prompt.id === id);
}

export function randomPrompt(exceptId?: string): Prompt {
  const pool = PROMPTS.filter((prompt) => prompt.id !== exceptId);
  return pool[Math.floor(Math.random() * pool.length)];
}

